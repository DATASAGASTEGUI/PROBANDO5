package misrc;

public class MiMetodo {

    public static double sumar(double n1, double n2) {
        return n1 + n2;
    }
    
    public static double restar(double n1, double n2) {
        return n1 - n2;
    }
    
    public static double multiplicar(double n1, double n2) {
        return n1 * n2;
    }    

}
